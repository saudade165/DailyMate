-- Web Push for reminders.
--
-- How it fits together:
--   * The browser subscribes (Push API + service worker) and saves the subscription
--     with save_push_subscription(). Only well-known push services are accepted, so
--     the server never sends requests to arbitrary addresses.
--   * Every minute pg_cron calls private.push_enqueue_due(), which writes one row in
--     notification_deliveries per (device, reminder, occurrence). The unique key makes
--     this idempotent: running twice never sends twice.
--   * The push-dispatch Edge Function claims pending rows (push_claim), sends them,
--     and reports the result (push_report): sent / retry with back-off / expired.
--   * VAPID keys are generated by the Edge Function and stored in Supabase Vault.
--     The private key never leaves the server.

-- ---- Subscriptions -------------------------------------------------------------------

create table public.push_subscriptions (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references auth.users (id) on delete cascade,
  endpoint        text not null unique check (char_length(endpoint) <= 1000),
  p256dh          text not null check (char_length(p256dh) between 80 and 120),
  auth_secret     text not null check (char_length(auth_secret) between 16 and 40),
  device_label    text not null default '' check (char_length(device_label) <= 100),
  created_at      timestamptz not null default now(),
  last_success_at timestamptz,
  last_failure_at timestamptz,
  failure_count   integer not null default 0,
  disabled_at     timestamptz,
  disabled_reason text
);
create index push_subscriptions_user on public.push_subscriptions (user_id) where disabled_at is null;

alter table public.push_subscriptions enable row level security;
create policy "own devices: read" on public.push_subscriptions for select to authenticated using ((select auth.uid()) = user_id);
revoke all on public.push_subscriptions from anon, authenticated;
-- People can see their devices, but not the keys. Changes go through the functions below.
grant select (id, device_label, created_at, last_success_at, last_failure_at, disabled_at, disabled_reason)
  on public.push_subscriptions to authenticated;

-- Push services used by Chrome/Edge/Android (FCM), Firefox (Mozilla), Edge (WNS) and Safari/iOS (Apple).
create function private.is_push_endpoint(p_endpoint text) returns boolean
language sql immutable set search_path = '' as $$
  select p_endpoint ~ '^https://(fcm\.googleapis\.com|android\.googleapis\.com|[a-z0-9.-]+\.push\.services\.mozilla\.com|[a-z0-9.-]+\.notify\.windows\.com|web\.push\.apple\.com|[a-z0-9.-]+\.push\.apple\.com)/';
$$;

create function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_label text default '')
returns uuid language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); sid uuid;
begin
  if uid is null then raise exception 'not signed in' using errcode = '28000'; end if;
  if not private.is_push_endpoint(p_endpoint) then raise exception 'unsupported push service' using errcode = '22023'; end if;
  -- The same browser can only belong to whoever is signed in on it now.
  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth_secret, device_label)
  values (uid, p_endpoint, p_p256dh, p_auth, left(coalesce(p_label, ''), 100))
  on conflict (endpoint) do update
    set user_id = excluded.user_id, p256dh = excluded.p256dh, auth_secret = excluded.auth_secret,
        device_label = excluded.device_label, disabled_at = null, disabled_reason = null, failure_count = 0,
        created_at = case when public.push_subscriptions.user_id = excluded.user_id
                          then public.push_subscriptions.created_at else now() end
  returning id into sid;
  return sid;
end $$;

-- Removes a device by its push address (this browser) or by id (any of my devices).
create function public.remove_push_subscription(p_endpoint text default null, p_id uuid default null)
returns integer language plpgsql security definer set search_path = '' as $$
declare n integer;
begin
  if auth.uid() is null then raise exception 'not signed in' using errcode = '28000'; end if;
  delete from public.push_subscriptions
   where user_id = auth.uid() and (endpoint = p_endpoint or id = p_id);
  get diagnostics n = row_count;
  return n;
end $$;

-- ---- Deliveries (idempotency + tracking) -----------------------------------------------

create table public.notification_deliveries (
  id              bigint generated always as identity primary key,
  user_id         uuid not null references auth.users (id) on delete cascade,
  subscription_id uuid not null references public.push_subscriptions (id) on delete cascade,
  kind            text not null check (kind in ('reminder', 'test')),
  reminder_id     text not null default '',
  occurrence_key  text not null,
  status          text not null default 'pending'
                  check (status in ('pending', 'sending', 'sent', 'retry', 'failed', 'expired')),
  attempts        integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  locked_until    timestamptz,
  http_status     integer,
  last_error      text,
  created_at      timestamptz not null default now(),
  sent_at         timestamptz,
  unique (subscription_id, kind, reminder_id, occurrence_key)
);
create index notification_deliveries_work on public.notification_deliveries (next_attempt_at)
  where status in ('pending', 'retry', 'sending');
create index notification_deliveries_user_kind on public.notification_deliveries (user_id, kind, created_at);
alter table public.notification_deliveries enable row level security;
revoke all on public.notification_deliveries from anon, authenticated;

-- ---- When is a reminder due? ---------------------------------------------------------------
-- The latest moment at or before p_now when this reminder should alert, or null.
-- Repeating reminders alert for every occurrence until the person marks one done,
-- using the same rules as the app (js/repeat.js): monthly/yearly keep the original
-- day, or the month's last day when it is shorter.

create function private.latest_occurrence(p_date date, p_time text, p_tz text, p_repeat text, p_now timestamptz)
returns timestamptz language plpgsql stable set search_path = '' as $$
declare
  t time := p_time::time;
  base timestamptz := (p_date + t) at time zone p_tz;
  local_now timestamp := p_now at time zone p_tz;
  cand date := (p_now at time zone p_tz)::date;
  occ date;
  anchor int := extract(day from p_date);
  step int; months int; m date;
begin
  if base > p_now then return null; end if;
  if p_repeat is null then return base; end if;
  if local_now::time < t then cand := cand - 1; end if;
  if cand <= p_date then return base; end if;
  case p_repeat
    when 'daily' then occ := cand;
    when 'weekly' then occ := cand - ((cand - p_date) % 7);
    when 'weekdays' then
      occ := cand;
      while occ > p_date and extract(isodow from occ) > 5 loop occ := occ - 1; end loop;
    else
      step := case p_repeat when 'monthly' then 1 else 12 end;
      months := ((extract(year from cand) * 12 + extract(month from cand))
               - (extract(year from p_date) * 12 + extract(month from p_date)))::int;
      months := months - (months % step);
      loop
        m := (date_trunc('month', p_date) + make_interval(months => months))::date;
        occ := m + (least(anchor, extract(day from (m + interval '1 month - 1 day'))::int) - 1);
        exit when occ <= cand or months <= 0;
        months := months - step;
      end loop;
      if occ > cand then occ := p_date; end if;
  end case;
  return (occ + t) at time zone p_tz;
end $$;

create function private.reminder_due_at(r public.reminders, p_now timestamptz)
returns timestamptz language plpgsql stable set search_path = '' as $$
declare occ timestamptz;
begin
  if r.done or r.deleted_at is not null then return null; end if;
  occ := private.latest_occurrence(r.date, r.time, r.tz, r.repeat, p_now);
  -- Snoozed past this occurrence: alert at the snooze time instead, once it arrives.
  if r.snoozed_until is not null and r.snoozed_until > coalesce(occ, '-infinity') then
    return case when r.snoozed_until <= p_now then r.snoozed_until end;
  end if;
  return occ;
end $$;

-- Queues every due reminder for every active device of its owner. Safe to run often.
create function private.push_enqueue_due(p_now timestamptz default now())
returns integer language plpgsql security definer set search_path = '' as $$
declare n integer;
begin
  insert into public.notification_deliveries (user_id, subscription_id, kind, reminder_id, occurrence_key, next_attempt_at)
  select r.user_id, s.id, 'reminder', r.id, (extract(epoch from d.at) * 1000)::bigint::text, p_now
    from public.reminders r
    cross join lateral (select private.reminder_due_at(r, p_now) as at) d
    join public.push_subscriptions s
      on s.user_id = r.user_id and s.disabled_at is null
     and s.created_at <= d.at + interval '5 minutes' -- no burst of old reminders right after enabling
   where r.alert_at <= p_now
     and (r.repeat is not null or r.alert_at > p_now - interval '6 hours')
     and d.at is not null
     and d.at > p_now - interval '6 hours' -- don't send reminders that are hours late
  on conflict (subscription_id, kind, reminder_id, occurrence_key) do nothing;
  get diagnostics n = row_count;
  return n;
end $$;

-- Claims up to p_limit deliveries for sending and returns what the sender needs.
create function public.push_claim(p_limit int default 100)
returns table (delivery_id bigint, kind text, attempts int, endpoint text, p256dh text, auth_secret text,
               title text, body text, reminder_id text, occurrence_key text)
language plpgsql security definer set search_path = '' as $$
begin
  return query
  with c as (
    select d.id from public.notification_deliveries d
     where (d.status in ('pending', 'retry') and d.next_attempt_at <= now())
        or (d.status = 'sending' and d.locked_until < now())
     order by d.id limit p_limit
     for update skip locked
  )
  update public.notification_deliveries d
     set status = 'sending', attempts = d.attempts + 1, locked_until = now() + interval '2 minutes'
    from c
    join public.notification_deliveries x on x.id = c.id
    join public.push_subscriptions s on s.id = x.subscription_id
    left join public.reminders r on r.user_id = x.user_id and r.id = x.reminder_id and x.kind = 'reminder'
   where d.id = c.id
  returning d.id, d.kind, d.attempts, s.endpoint, s.p256dh, s.auth_secret,
            case when d.kind = 'test' then 'DailyMate test notification' else coalesce(r.title, 'Reminder') end,
            case when d.kind = 'test' then 'Notifications are working on this device.'
                 else coalesce(nullif(r.notes, ''), 'DailyMate reminder') end,
            d.reminder_id, d.occurrence_key;
end $$;

-- Records the outcome of one send attempt.
--   p_outcome: 'sent' | 'gone' (subscription expired) | 'retry' (temporary) | 'failed' (permanent)
create function public.push_report(p_delivery_id bigint, p_outcome text, p_http int default null, p_error text default null)
returns void language plpgsql security definer set search_path = '' as $$
declare d public.notification_deliveries;
begin
  select * into d from public.notification_deliveries where id = p_delivery_id for update;
  if not found then return; end if;
  if p_outcome = 'sent' then
    update public.notification_deliveries set status = 'sent', sent_at = now(), http_status = p_http,
           last_error = null, locked_until = null where id = d.id;
    update public.push_subscriptions set last_success_at = now(), failure_count = 0 where id = d.subscription_id;
  elsif p_outcome = 'gone' then
    update public.notification_deliveries set status = 'expired', http_status = p_http,
           last_error = left(p_error, 500), locked_until = null where id = d.id;
    update public.push_subscriptions set disabled_at = now(), disabled_reason = 'expired' where id = d.subscription_id;
  else
    update public.notification_deliveries
       set status = case when p_outcome = 'retry' and d.attempts < 3 and d.created_at > now() - interval '1 hour'
                         then 'retry' else 'failed' end,
           next_attempt_at = now() + make_interval(mins => power(2, d.attempts)::int),
           http_status = p_http, last_error = left(p_error, 500), locked_until = null
     where id = d.id;
    update public.push_subscriptions
       set last_failure_at = now(), failure_count = failure_count + 1,
           disabled_at = case when failure_count + 1 >= 10 then now() end,
           disabled_reason = case when failure_count + 1 >= 10 then 'failing' end
     where id = d.subscription_id and disabled_at is null;
  end if;
end $$;

-- Queues a test notification for the user's devices (at most 5 per 10 minutes).
create function public.push_enqueue_test(p_user uuid, p_endpoint text default null)
returns integer language plpgsql security definer set search_path = '' as $$
declare recent int; n int; k text := gen_random_uuid()::text;
begin
  select count(distinct occurrence_key) into recent from public.notification_deliveries
   where user_id = p_user and kind = 'test' and created_at > now() - interval '10 minutes';
  if recent >= 5 then return -1; end if;
  insert into public.notification_deliveries (user_id, subscription_id, kind, occurrence_key)
  select p_user, s.id, 'test', k from public.push_subscriptions s
   where s.user_id = p_user and s.disabled_at is null and (p_endpoint is null or s.endpoint = p_endpoint);
  get diagnostics n = row_count;
  return n;
end $$;

-- ---- VAPID keys and the dispatcher secret (Supabase Vault) --------------------------------

select vault.create_secret(encode(extensions.gen_random_bytes(32), 'hex'), 'push_dispatch_secret',
                           'Sent by pg_cron to the push-dispatch function');

create function public.get_push_public_key() returns text
language sql stable security definer set search_path = '' as $$
  select decrypted_secret from vault.decrypted_secrets where name = 'push_vapid_public';
$$;

create function public.push_server_config() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'public',     (select decrypted_secret from vault.decrypted_secrets where name = 'push_vapid_public'),
    'privateJwk', (select decrypted_secret from vault.decrypted_secrets where name = 'push_vapid_private'),
    'dispatchSecret', (select decrypted_secret from vault.decrypted_secrets where name = 'push_dispatch_secret'));
$$;

-- Stores a newly generated key pair once. Returns false if keys already exist.
create function public.push_store_vapid(p_public text, p_private_jwk text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtext('push_vapid'));
  if exists (select 1 from vault.secrets where name = 'push_vapid_public') then return false; end if;
  perform vault.create_secret(p_private_jwk, 'push_vapid_private', 'VAPID private key (JWK) for Web Push');
  perform vault.create_secret(p_public, 'push_vapid_public', 'VAPID public key (base64url) for Web Push');
  return true;
end $$;

